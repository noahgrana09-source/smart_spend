  /// In en, this message translates to:
  /// **'Continue with Google'**
  String get googleButton;

  /// No description provided for @goToRegister.
  ///
  /// In en, this message translates to:
  /// **'Don\'t have an account? Sign up'**
  String get goToRegister;

